// Helper to construct a fully detailed, standardized product item
function createProduct({
  id,
  name,
  brand,
  category,
  categoryName,
  subcategory,
  childCategory,
  department = "unisex",
  gender = "unisex",
  section = "all",
  sellerId = "seller-1",
  sellerName = "GoMo Verified Partner",
  price,
  mrp,
  stock = 35,
  rating = 4.8,
  reviews = 150,
  isFeatured = true,
  isBestseller = true,
  dealType = "daily_deal",
  thumbnail,
  images = [],
  description,
  features,
  specifications,
  tags,
}) {
  const allImages = images.length > 0 ? images : [thumbnail];
  const discount = Math.round(((mrp - price) / mrp) * 100);

  return {
    id,
    product_id: id,
    name,
    title: name,
    brand,
    category,
    category_name: categoryName,
    subcategory,
    childCategory: childCategory || subcategory,
    department,
    gender,
    section,
    seller_id: sellerId,
    seller_name: sellerName,
    price,
    mrp,
    discount_percentage: discount,
    stock_quantity: stock,
    in_stock: true,
    is_active: true,
    rating,
    reviews_count: reviews,
    is_featured: isFeatured,
    is_bestseller: isBestseller,
    deal_type: dealType,
    thumbnail,
    images: allImages,
    pi_images: allImages.map((u) => ({ image_url: u })),
    description,
    features: features || [
      `100% Genuine product directly certified by ${brand}`,
      "Passed rigorous multi-stage quality assurance tests",
      "Hassle-free 7-day doorstep replacement guarantee",
      "Eco-friendly secure transit packaging",
    ],
    specifications: specifications || {
      Category: categoryName,
      Subcategory: childCategory || subcategory,
      Brand: brand,
      Warranty: "1 Year Standard Brand Warranty",
    },
    delivery_info: {
      free_delivery: price >= 499,
      estimated_days: 2,
      return_days: 7,
      cod_available: true,
      courier: "BlueDart Express",
    },
    tags: tags || `${category}, ${subcategory}, ${brand}, curated, premium`,
  };
}

